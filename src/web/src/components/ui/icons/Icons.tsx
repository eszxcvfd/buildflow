/**
 * Web redesign — kho icon stroke-SVG dùng chung cho shell + projects
 * workspace (port path lucide trong mẫu, viewBox 24, stroke currentColor).
 * Không thêm dependency icon runtime (nhất quán với AppShell inline-SVG).
 */

interface IconProps {
  size?: number;
  className?: string;
}

function Svg({
  size = 16,
  className,
  children,
  strokeWidth = 2,
}: IconProps & { children: React.ReactNode; strokeWidth?: number }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      {children}
    </svg>
  );
}

